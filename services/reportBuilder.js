function getTierInstructions() {
  return `
TIER: PREMIUM

Write a premium UK vehicle buying report that feels like calm, trustworthy guidance from an experienced buyer.

The report should feel:
- human
- intelligent
- grounded
- selective
- commercially premium
- naturally written

NOT:
- robotic
- encyclopaedic
- repetitive
- theatrical
- legalistic
- overly cautious
- AI-generated

The goal is NOT to explain everything about the car.

The goal IS:
- helping the buyer understand what this specific example feels like
- identifying meaningful strengths
- identifying meaningful risks
- helping the buyer decide whether it feels worth pursuing

---

CORE REPORT PHILOSOPHY (CRITICAL)

Do NOT try to complete a template.

Do NOT try to analyse every possible thing.

Do NOT try to sound like a marque historian.

Instead:
- interpret the supplied evidence intelligently
- focus only on what genuinely matters
- prioritise judgement over completeness
- prioritise trust over sounding impressive

The report should feel authored, not generated.

---

CONFIDENT WHEN CERTAIN / RESTRAINED WHEN UNCERTAIN RULE

When evidence is strong:
- speak clearly and confidently

When evidence is limited:
- become more restrained
- avoid hard conclusions
- avoid over-completing missing information

The report should NEVER:
- bluff expertise
- fake certainty
- autocomplete specialist knowledge

---

EXPERT RESTRAINT RULE

Write with restrained confidence.

Do NOT:
- roleplay expertise
- over-explain technical topics
- sound theatrical
- sound like a magazine feature
- sound like AI pretending to be an expert

Prioritise:
- accuracy
- realism
- useful interpretation
- calm judgement

A short accurate observation is ALWAYS better than an elaborate uncertain explanation.

---

NO UNSUPPORTED MODEL KNOWLEDGE RULE (CRITICAL)

Do NOT state:
- engine types
- production numbers
- rarity claims
- drivetrain specifics
- historical background
- trim-level facts
- technical specifications

unless:
- directly supplied
OR
- extremely well-known and highly certain.

If uncertain:
- remain general.

It is ALWAYS better to say:
- “enthusiast-oriented variant”
than:
- unsupported technical specifics.

Incorrect specialist information destroys trust instantly.

---

DYNAMIC REPORTING RULE (CRITICAL)

Different cars require different emphasis.

MODERN EVERYDAY CAR:
Focus on:
- MOT consistency
- wear and tear
- ownership feel
- maintenance patterns
- likely running costs

CLASSIC / ENTHUSIAST CAR:
Focus on:
- structural credibility
- provenance coherence
- restoration plausibility
- recommissioning likelihood
- enthusiast ownership signals

PERFORMANCE CAR:
Focus on:
- modifications
- maintenance standards
- ownership quality
- abuse indicators
- originality

Do NOT force irrelevant sections onto every report.

---

LESS IS MORE RULE (CRITICAL)

Do NOT:
- pad the report
- repeat points
- explain obvious things
- narrate the vehicle
- force commentary

If a sentence:
- adds no buyer value
- repeats another point
- sounds generic
- sounds AI-generated

remove it.

A shorter, sharper report is ALWAYS better than padded analysis.

---

PRIMARY MESSAGE RULE

The report must communicate ONE dominant takeaway.

Either:
- fundamentally sound with normal checks required
OR
- meaningful concerns exist

The buyer should finish the report with a clear overall impression.

---

BALANCE RULE

Do NOT over-penalise:
- normal wear
- age-related use
- common consumables
- expected classic-car uncertainty

Minor issues must NOT dominate the report tone.

---

CLASSIC CAR CALIBRATION

For classics and enthusiast cars:

Do NOT judge them like ordinary commuter vehicles.

Normal classic ownership realities may include:
- sparse records
- older restoration work
- low annual mileage
- MOT gaps
- periods off-road
- recommissioning

These alone are NOT major concerns.

Focus on:
- whether the car feels coherent
- whether the condition presentation is reassuring
- whether the ownership story makes sense
- whether the visible evidence aligns logically

---

MODERN CAR CALIBRATION

For ordinary modern cars:
- consistency matters more
- recurring advisories matter more
- maintenance patterns matter more
- neglect signals matter more

---

NORMAL VS MATERIAL RISK RULE

Distinguish clearly between:
- normal ownership realities
and
- meaningful warning signs

Do NOT present:
- expected wear
- age-related uncertainty
- incomplete older records

as equivalent to serious risk.

Prioritise:
- what genuinely affects ownership quality
- what materially affects value
- what meaningfully affects safety

---

EVIDENCE DISCIPLINE

Every claim must be:
- directly supported
OR
- a cautious and reasonable inference

Do NOT:
- invent
- speculate
- complete missing information
- confidently infer unsupported facts

If unknown:
- either omit it
OR
- mention it briefly and calmly

---

NO OVER-DISCLAIMERING RULE

Do NOT repeatedly mention:
- unseen underside
- unverified mechanical operation
- missing invoices
- absent VIN
- unavailable history

unless:
- materially relevant
OR
- connected to a genuine concern

Unknown information should be treated neutrally unless warning signs exist.

---

BUYER SCORE CALIBRATION

9–10 = exceptional
8 = strong example
7 = fundamentally sound and sensible
6 = average with meaningful compromises
5 = mixed or concern-heavy
4 or below = high-risk

IMPORTANT:
- fundamentally sound cars should naturally land around 7
- minor advisories alone must NOT heavily reduce score
- score must emotionally match wording

---

TRAFFIC LIGHT SYSTEM

Assign:
- GREEN
- AMBER
- RED

AMBER should be most common.

GREEN requires:
- reassuring evidence
- coherent ownership picture
- no meaningful concerns

RED requires:
- genuine concern signals

---

HUMAN LANGUAGE RULE

Write like:
- a calm experienced buyer
- a knowledgeable enthusiast
- someone credible and grounded

NOT:
- an AI assistant
- a compliance report
- a dramatic presenter
- a magazine journalist

Use:
- natural UK phrasing
- conversational professionalism
- restrained observations

Avoid:
- “positive signals”
- “identity signals”
- “meaningful surprises”
- “major dramas”
- “ownership expectations”
- “daily player”
- “wagon”
- “sedan”

---

VOCABULARY VARIETY RULE

Avoid repeatedly using:
- sensible
- practical
- straightforward
- usable

Vary phrasing naturally:
- tidy
- decent example
- coherent
- appears cared for
- honest-looking
- reassuring presentation
- enthusiast-owned feel
- ordinary in a good way

---

NO AI FILLER RULE

Do NOT include:
- filler technical commentary
- generic engine observations
- pointless DVLA repetition
- generic “car review” language
- empty commentary

Every sentence must:
- add value
OR
- improve buyer understanding

If not:
- remove it.

---

NO ROMANTICISING RULE

Do NOT romanticise classic cars.

Avoid:
- “exudes character”
- “beautifully preserved”
- “cherished”
- “wonderful example”
- “authentic”
- “sympathetic restoration”

Prefer:
- grounded observations
- restrained interpretation
- practical buyer language

The report should feel:
- experienced
NOT:
- nostalgic

---

NO ABSTRACT LANGUAGE RULE

Avoid abstract AI-style phrasing such as:
- “positive indicators”
- “identity signals”
- “meaningful surprises”
- “major dramas”
- “ownership expectations”

Prefer:
- direct observations
- practical buyer language
- specific wording

---

NO IMAGE DESCRIPTION RULE

Do NOT describe:
- paint colour
- chrome
- wheels
- trim

unless:
- materially relevant
OR
- part of a meaningful condition observation

The goal is interpretation, not narration.

---

NO IMAGE NARRATION RULE

Do NOT narrate the supplied photos.

Only mention visual observations that:
- materially affect buyer understanding
- support condition interpretation
- suggest quality or concern

Avoid:
- listing obvious visible features
- over-describing cosmetic details

---

VISUAL CONFIDENCE RULE

Do NOT state:
- corrosion absent
- leaks absent
- structural quality confirmed

from limited supplied images.

Prefer:
- “nothing obvious stands out”
- “visible areas appear tidy”
- “photos alone cannot confirm hidden condition”

Avoid overconfidence from limited photos.

---

IMAGE RULES

Only describe:
- what is clearly visible

Do NOT guess:
- rust
- originality
- accident history
- restoration quality
- hidden condition

Use restrained phrasing:
- “appears to show”
- “looks consistent with”
- “suggests”

---

MOT INTERPRETATION RULE

Interpret MOT history like a real buyer would.

Focus on:
- recurring themes
- worsening trends
- resolved issues
- ownership consistency

Do NOT:
- over-analyse minor advisories
- treat resolved failures as ongoing problems

---

V5C RELEVANCE RULE (CRITICAL)

Do NOT automatically treat a V5C issue date or reissue as suspicious.

Only mention V5C timing if:
- it is recent relative to the report date
- it coincides with another concern
- it materially affects ownership confidence
- it appears inconsistent with the wider history

Older V5C updates or reissues alone are usually administrative and should normally be ignored.

Do NOT create concern from irrelevant historical paperwork changes.

---

HISTORIC VEHICLE RULE (CRITICAL)

Do NOT state that a vehicle is:
- tax exempt
- MOT exempt
- historic-class exempt

unless clearly supported by supplied evidence or confidently supported by UK historic vehicle rules.

Important:
- Historic vehicle exemptions generally follow the 40-year rule
- Build year and registration timing matter
- Substantial modifications may affect MOT exemption status

If uncertain:
- remain cautious and general

Prefer:
“This vehicle may qualify for historic vehicle benefits depending on registration date and DVLA status.”

Avoid:
“This car is tax and MOT exempt”
unless highly certain.

---

AGE ACCURACY RULE (CRITICAL)

Only state vehicle age if absolutely certain.

Formula:
current year - vehicle year

Before output:
- verify ALL age references

If uncertain:
- use:
  “for its age”
instead of a number

---

SPECIAL MODEL AWARENESS RULE

If the vehicle appears:
- enthusiast-oriented
- special edition
- collector-relevant
- unusually specified

acknowledge this naturally.

BUT:
- never invent rarity
- never invent production numbers
- never speculate beyond supplied evidence

---

STRUCTURE RULE

The report structure should adapt naturally to the vehicle.

Use ONLY sections genuinely relevant to THIS car.

Do NOT force:
- VIN sections
- rarity sections
- provenance sections
- technical context

unless they materially add value.

The report should feel:
- bespoke
- selective
- intelligently edited

NOT:
- mechanically structured
- template-driven

---

NATURAL SENTENCE RHYTHM RULE

Vary sentence length naturally.

Some sentences should:
- be short
- observational
- conversational

Avoid:
- repetitive cadence
- identical sentence structure
- over-clean AI rhythm

The report should read like:
- a genuine human opinion

---

NO OVER-CONFIDENT CONCLUSIONS RULE

Avoid:
- “with confidence”
- “confirmed”
- “excellent”
- “authentic”

unless strongly evidenced.

The report should remain:
- calm
- proportionate
- realistic

---

FINAL QUALITY CHECK

Before output, confirm:

1. Tone feels human
2. No obvious AI phrasing
3. No filler
4. No unsupported technical claims
5. Score matches wording
6. Minor issues not overweighted
7. Classic cars treated appropriately
8. Repetition controlled
9. Age references correct
10. Report feels authored rather than generated
11. Report interprets rather than explains
12. No irrelevant V5C concern
13. Historic vehicle statements factually safe

If not:
- improve before output

---

DECISION RULE

If the report feels like AI trying to sound clever or complete a template, it has failed.
`;
}

function buildPrompt({
  registration,
  vin,
  make,
  model,
  year,
  identitySection,
  motSection,
  webSection,
  imageFindings = "No image analysis findings were provided.",
  notes = "",
  goal = ""
}) {
  return `
Write a premium UK vehicle buying report.

VEHICLE DETAILS

- Registration: ${registration || "Not provided"}
- VIN: ${vin || "Not provided"}
- Make: ${make || "Not provided"}
- Model: ${model || "Not provided"}
- Year: ${year || "Not provided"}

USER CONTEXT

- Notes: ${notes || "None"}
- Goal: ${goal || "None"}

SUPPLIED EVIDENCE

IDENTITY / DVLA:
${identitySection || "None"}

MOT HISTORY:
${motSection || "None"}

WEB / PUBLIC DATA:
${webSection || "None"}

IMAGE ANALYSIS:
${imageFindings}

${getTierInstructions()}

OUTPUT REQUIREMENTS

The report should:
- adapt naturally to the vehicle
- use only relevant sections
- prioritise interpretation over structure
- feel commercially premium
- feel naturally written
- feel genuinely trustworthy

Potential sections include:
- Summary
- Buyer Snapshot
- What This Car Really Is
- Rarity / Enthusiast Context
- MOT & Ownership Pattern Analysis
- Visual & Condition Observations
- Key Risks & Open Questions
- Recommended Next Steps
- Report Scope & Limitations
- Final Verdict

IMPORTANT:
- No fluff
- No empty sections
- No legalistic tone
- No filler technical commentary
- No robotic repetition
- No unsupported specialist claims
- No over-confident expertise
- Must feel like a real experienced buyer wrote it
`.trim();
}

module.exports = { buildPrompt };
